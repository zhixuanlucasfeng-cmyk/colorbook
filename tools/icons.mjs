// Multicolor logo: a 6x6 pixel heart-ish mosaic.
const LOGO = [
  '.TT.SS.',
  'TTTSSSS',
  'TTMMSSS',
  'TMMMMSS',
  '.MMMMS.',
  '..MMM..',
  '...M...',
];
const LOGO_COLORS = { T: '#ff5a36', S: '#ffc93c', M: '#34c79a' };

const svg = (rows, color) => {
  const h = rows.length, w = Math.max(...rows.map(r => r.length));
  let rects = '';
  rows.forEach((r, y) => [...r].forEach((c, x) => {
    const fill = typeof color === 'string' ? (c === '#' ? color : null) : color[c];
    if (fill) rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`;
  }));
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges">${rects}</svg>`;
};

for (const [name, art] of Object.entries(ART)) {
  const rows = art.trim().split('\n');
  if (rows.length !== 12 || rows.some(r => r.length !== 12)) throw new Error(`${name} is not 12x12`);
  fs.writeFileSync(`mp/assets/${name}-ink.svg`, svg(rows, INK));
  fs.writeFileSync(`mp/assets/${name}-paper.svg`, svg(rows, PAPER));
}
fs.writeFileSync('mp/assets/logo.svg', svg(LOGO, LOGO_COLORS));
