#!/bin/sh
# Subset Fusion Pixel Font (OFL) to the characters the mini program uses, embed as base64 in mp/font.wxss.
# Usage: tools/font.sh <fusion-pixel-12px-proportional-zh_hans.otf.woff2> <path to pyftsubset>
set -e
SRC="$1"; SUBSET="${2:-pyftsubset}"
CHARS=$(cat mp/pages/*/*.wxml mp/pages/*/*.js mp/app.json mp/pages/*/*.json | tr -d '\n')
TEXT="${CHARS}0123456789%/.-+ 号格色作品完成照片"
"$SUBSET" "$SRC" --text="$TEXT" --flavor=woff --output-file=/tmp/px-sub.woff --layout-features='*'
B64=$(base64 < /tmp/px-sub.woff | tr -d '\n')
printf '/* Fusion Pixel Font 12px, SIL Open Font License 1.1 (see assets/OFL.txt). Generated by tools/font.sh */\n@font-face { font-family: "px"; src: url("data:font/woff;base64,%s") format("woff"); }\n' "$B64" > mp/font.wxss
echo "font.wxss: $(wc -c < mp/font.wxss) bytes"
